from pathlib import Path
from PIL import Image, ImageOps
import json
import sys

root = Path(__file__).resolve().parent.parent
manifest_file = root / 'artifacts/reference-downloads/manifest.json'
manifest = json.loads(manifest_file.read_text(encoding='utf-8'))
by_key = {item['key']: item for item in manifest['images']}
for index, item in enumerate([] if '--index-only' in sys.argv else manifest['images']):
    source = root / item['originalPath']
    target = root / 'public' / item['localPath'].lstrip('/')
    target.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(source) as opened:
        im = ImageOps.exif_transpose(opened)
        item['sourceWidth'], item['sourceHeight'] = im.size
        im.thumbnail((1600, 1600), Image.Resampling.LANCZOS)
        im = im.convert('RGBA' if 'A' in im.getbands() else 'RGB')
        im.save(target, format='WEBP', quality=80, method=6)
        item['width'], item['height'] = im.size
    with Image.open(target) as verification:
        verification.verify()
    item['previewBytes'] = target.stat().st_size
    if (index + 1) % 40 == 0:
        print(f"Optimized {index + 1}/{len(manifest['images'])}", flush=True)

preview = {}
for project in manifest['projects']:
    source_records = [record for record in project['records'] if record['images']]
    records = []
    for index in range(project['previewCount']):
        chosen = round(index * (len(source_records) - 1) / max(1, project['previewCount'] - 1))
        # Start the homepage example with a classroom photograph, not a chat screenshot.
        if project['id'] == 'mech' and index == 0:
            chosen = 2
        record = source_records[chosen]
        records.append({'sourceSequence': record['sequence'], 'images': [by_key[key]['localPath'] for key in record['images'][:3]]})
    preview[project['id']] = {'cover': by_key[project['cover']]['localPath'], 'records': records}

header = '// Generated by scripts/prepare-reference-images.py. External reference images for local preview only.\n'
header += 'export const referencePreviewImages: Record<string, { cover: string; records: { sourceSequence: number; images: string[] }[] }> = '
(root / 'src/data/reference-images.ts').write_text(header + json.dumps(preview, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
manifest['previewImageCount'] = len(set(src for project in preview.values() for record in project['records'] for src in record['images']))
manifest['previewBytes'] = sum(item['previewBytes'] for item in manifest['images'])
manifest['originalBytes'] = sum(item['originalBytes'] for item in manifest['images'])
manifest['optimization'] = 'EXIF orientation applied; metadata stripped; longest edge 1600px; WebP quality 80.'
manifest_file.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
(root / 'public/images/reference/provenance.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps({key: manifest[key] for key in ['previewImageCount', 'previewBytes', 'originalBytes']}, ensure_ascii=False))
