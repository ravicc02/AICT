function buildDossier(projectId: string, seeds: RecordSeed[]): ProjectDossier {
  const records = seeds.map(
    (
      [title, heading, summary, teacher, child, outcome],
      index,
    ): CreationRecord => ({
      id: `record-${String(index + 1).padStart(2, "0")}`,
      title,
      heading,
      summary,
      teacher,
      child,
      outcome,
      kind:
        index === 2 || (projectId === "mech" && index === 7)
          ? "课后更新"
          : "课堂记录",
      media: referencePreviewImages[projectId].records[index].images.map(
        (src, imageIndex) => ({
          src,
          caption: `参考图片 ${imageIndex + 1}`,
        }),
      ),
    }),
  );
  const last = records.length - 1;
  const sources =
    projectId === "mech"
      ? [
          [0, 9],
          [1, 4],
          [3, 8],
          [5, 7],
          [4, 6],
          [1, 7],
        ]
      : [
          [0, last],
          [0, 1],
          [1, last],
          [Math.max(2, last - 1), last],
          [1, 2],
          [0, last - 1],
        ];
  return {
    projectId,
    isSample: true,
    records,
    dimensions: dimensions.map((name, i) => ({
      name,
      value: sampleValues[projectId][i],
      observation: observations[projectId][i],
      recordIds: [...new Set(sources[i].map((index) => records[index].id))],
    })),
  };
}
